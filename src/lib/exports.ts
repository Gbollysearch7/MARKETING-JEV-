import 'server-only';
import type { Task } from './repo';

export const REDIRECT_FORMATS = {
  csv: { label: 'CSV (source, target, code)', file: 'redirects.csv', type: 'text/csv' },
  htaccess: { label: 'Apache .htaccess', file: 'redirects.htaccess', type: 'text/plain' },
  nginx: { label: 'Nginx', file: 'redirects.nginx.conf', type: 'text/plain' },
  netlify: { label: 'Netlify _redirects', file: '_redirects', type: 'text/plain' },
  shopify: { label: 'Shopify URL redirects CSV', file: 'shopify-redirects.csv', type: 'text/csv' },
  wordpress: { label: 'WordPress Redirection plugin CSV', file: 'wordpress-redirection.csv', type: 'text/csv' },
} as const;
export type RedirectFormat = keyof typeof REDIRECT_FORMATS;

const q = (s: string) => `"${s.replace(/"/g, '""')}"`;

/** Redirect rules from approved Merge, Redirect and Prune tasks that have not been cancelled. */
export function redirectRules(tasks: Task[]) {
  return tasks
    .filter((t) => t.status !== 'cancelled' && t.brief.redirect && (t.brief.redirect.code === 410 || t.target))
    .map((t) => ({ from: t.path, to: t.brief.redirect!.code === 410 ? null : t.target, code: t.brief.redirect!.code }));
}

export function redirectFile(format: RedirectFormat, tasks: Task[]): string {
  const rules = redirectRules(tasks);
  switch (format) {
    case 'csv':
      return ['source,target,code', ...rules.map((r) => `${q(r.from)},${q(r.to ?? '')},${r.code}`)].join('\n');
    case 'htaccess':
      return ['# Generated by Rankcall', ...rules.map((r) => (r.code === 410 ? `Redirect gone ${r.from}` : `Redirect 301 ${r.from} ${r.to}`))].join('\n');
    case 'nginx':
      return ['# Generated by Rankcall. Include inside the server block.', ...rules.map((r) => (r.code === 410 ? `location = ${r.from} { return 410; }` : `location = ${r.from} { return 301 ${r.to}; }`))].join('\n');
    case 'netlify':
      return ['# Generated by Rankcall', ...rules.map((r) => (r.code === 410 ? `${r.from}  /404  410` : `${r.from}  ${r.to}  301`))].join('\n');
    case 'shopify':
      // Shopify redirects cannot return 410; pruned URLs are listed separately.
      return ['Redirect from,Redirect to', ...rules.filter((r) => r.code === 301).map((r) => `${q(r.from)},${q(r.to!)}`)].join('\n');
    case 'wordpress':
      return ['source,target,regex,code', ...rules.map((r) => `${q(r.from)},${q(r.to ?? '')},0,${r.code}`)].join('\n');
  }
}

export function tasksCsv(tasks: Task[]): string {
  const head = ['url_path', 'verdict', 'target', 'status', 'owner', 'due_date', 'forecast_low_clicks_month', 'forecast_high_clicks_month', 'summary', 'checklist', 'queries'];
  const rows = tasks.map((t) => [t.path, t.verdict, t.target ?? '', t.status, t.owner ?? '', t.due_date ?? '', t.forecast_low, t.forecast_high, t.brief.summary, t.brief.checklist.join(' | '), t.brief.queries.map((x) => x.query).join(' | ')]);
  return [head.join(','), ...rows.map((r) => r.map((c) => q(String(c))).join(','))].join('\n');
}
