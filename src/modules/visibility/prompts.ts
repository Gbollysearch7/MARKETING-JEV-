/** Prompt suggestions from Search Console data and page titles, and "does the site have a page for this prompt". */

const STOP = new Set(('a an and are as at be best better buy buying can cheap cheapest choose choosing compare do does find for from get good great guide how i if in is it me my near of on or should the their them there this to top uk us versus vs what when where which who why will with worth you your 2023 2024 2025 2026 2027 review reviews reviewed tested beginner beginners recommend recommended need').split(' '));

const stem = (w: string) => (w.length > 4 && w.endsWith('ies') ? `${w.slice(0, -3)}y` : w.length > 3 && w.endsWith('es') && /(ch|sh|x|ss)es$/.test(w) ? w.slice(0, -2) : w.length > 3 && w.endsWith('s') && !w.endsWith('ss') ? w.slice(0, -1) : w);

/** Content words of a text: lowercase, no stop words, simple plural stemming. */
export function contentTokens(text: string, exclude: string[] = []): string[] {
  const ex = new Set(exclude.flatMap((e) => e.toLowerCase().split(/[^\p{L}\p{N}]+/u)).filter(Boolean).map(stem));
  const out: string[] = [];
  for (const raw of text.toLowerCase().split(/[^\p{L}\p{N}]+/u)) {
    if (!raw || STOP.has(raw) || /^\d+$/.test(raw)) continue;
    const w = stem(raw);
    if (w.length < 2 || ex.has(w) || out.includes(w)) continue;
    out.push(w);
  }
  return out;
}

export type CoverageMatch = 'close' | 'partial' | 'none';
export interface Coverage { match: CoverageMatch; score: number; path: string | null; title: string | null }

/**
 * Whether the site has a page that covers the prompt, by token match against page titles.
 * Score = share of the prompt's content words found in the title (and URL path). Close at 0.8 or more,
 * partial from 0.5. Brand words are ignored, so "is Sample Outdoors good for tents" matches a tents page.
 */
export function coverageFor(prompt: string, pages: { path: string; title: string | null }[], brandWords: string[] = []): Coverage {
  const want = contentTokens(prompt, brandWords);
  if (!want.length) return { match: 'none', score: 0, path: null, title: null };
  let best: Coverage = { match: 'none', score: 0, path: null, title: null };
  for (const p of pages) {
    const have = new Set(contentTokens(`${p.title ?? ''} ${p.path.replace(/[-/_]+/g, ' ')}`, brandWords));
    const hit = want.filter((w) => have.has(w)).length;
    const score = hit / want.length;
    if (score > best.score || (score === best.score && best.path && p.path.length < best.path.length)) best = { match: 'none', score, path: p.path, title: p.title };
  }
  const match: CoverageMatch = best.score >= 0.8 ? 'close' : best.score >= 0.5 ? 'partial' : 'none';
  return match === 'none' ? { match, score: best.score, path: null, title: null } : { ...best, match };
}

