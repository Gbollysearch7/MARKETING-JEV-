const MODIFIERS = /\b(best|top|cheap|cheapest|buy|how to choose|how to|review|reviews|guide|uk|for beginners|near me|deals?|sale|20\d\d)\b/g;

/** "best hiking boots uk" -> "hiking boots". Returns null for queries with no topic left. */
export function topicOf(query: string, brandWords: string[] = []): string | null {
  let s = ` ${query.toLowerCase()} `.replace(/[^\p{L}\p{N}\s&'-]/gu, ' ');
  for (const b of brandWords) if (b.trim().length > 1) s = s.split(b.toLowerCase()).join(' ');
  s = s.replace(MODIFIERS, ' ').replace(/\b(in|for|the|a|an|of|and|vs|versus)\s*$/g, ' ').replace(/\s+/g, ' ').trim();
  if (s.length < 3 || /^\d+$/.test(s) || s.split(' ').length > 5) return null;
  return s;
}

/** Topic from a page title such as "Best tents in 2024: tested and reviewed" or "How to choose a rucksack". */
export function topicFromTitle(title: string): string | null {
  const t = title.replace(/[:|–—-].*$/, '').trim();
  const m = /^(?:the\s+)?(?:best|top \d+)\s+(.+?)(?:\s+(?:in|for)\s+\d{4})?$/i.exec(t) ?? /^how to choose\s+(?:a |an |the )?(.+)$/i.exec(t);
  return m ? m[1].toLowerCase().trim() : null;
}

export interface Suggestion { text: string; group: string; why: string }

/**
 * Buyer-style prompt suggestions built from templates. Topics are ranked by Search Console impressions,
 * topped up from page titles. Nothing here is generated by a model.
 */
export function suggestPrompts(input: {
  brand: string;
  competitors: string[];
  queries: { query: string; impressions: number }[];
  titles: string[];
  existing: string[];
  limit?: number;
}): Suggestion[] {
  const brandWords = [input.brand];
  const score = new Map<string, number>();
  for (const q of input.queries) {
    const t = topicOf(q.query, brandWords);
    if (t) score.set(t, (score.get(t) ?? 0) + Math.max(1, q.impressions));
  }
  for (const title of input.titles) {
    const t = topicFromTitle(title);
    if (t && t.split(' ').length <= 4) score.set(t, (score.get(t) ?? 0) + 1);
  }
  // Merge singular and plural forms of the same topic.
  const byKey = new Map<string, { topic: string; score: number }>();
  for (const [topic, s] of score) {
    const key = contentTokens(topic).join(' ');
    if (!key) continue;
    const cur = byKey.get(key);
    if (!cur) byKey.set(key, { topic, score: s });
    else { cur.score += s; if (topic.length > cur.topic.length) cur.topic = topic; }
  }
  const topics = [...byKey.values()].sort((a, b) => b.score - a.score).slice(0, 8).map((t) => t.topic);
  const have = new Set(input.existing.map((e) => e.toLowerCase().trim()));
  const out: Suggestion[] = [];
  const push = (text: string, group: string, why: string) => {
    const k = text.toLowerCase();
    if (have.has(k) || out.some((o) => o.text.toLowerCase() === k)) return;
    out.push({ text, group, why });
  };
  topics.forEach((t, i) => {
    push(`best ${t} for beginners`, t, 'Top Search Console topic');
    push(`is ${input.brand} good for ${t}`, t, 'Brand check on a core topic');
    if (i < 4) push(`where to buy ${t} in the UK`, t, 'Purchase intent');
  });
  // "{topic} vs {topic}" only for topics that share a word (e.g. two kinds of jacket), so pairs make sense.
  for (let i = 0; i < topics.length; i++) {
    for (let j = i + 1; j < topics.length; j++) {
      const a = contentTokens(topics[i]);
      const b = contentTokens(topics[j]);
      if (a.some((w) => b.includes(w))) push(`${topics[i]} vs ${topics[j]}`, topics[i], 'Comparison between related topics');
    }
  }
  for (const c of input.competitors.slice(0, 5)) push(`${input.brand} vs ${c}`, 'brand', 'Head to head with a competitor');
  return out.slice(0, input.limit ?? 30);
}
