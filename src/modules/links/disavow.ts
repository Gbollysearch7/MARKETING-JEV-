/** Google disavow file: one "domain:example.com" line per domain, with a header comment. */
export function disavowFile(domains: string[], site: { name: string; domain: string }, today: string): string {
  const uniq = [...new Set(domains.map((d) => d.toLowerCase().replace(/^www\./, '').trim()).filter(Boolean))].sort();
  return [
    `# Disavow file for ${site.domain} (${site.name}), generated by Rankcall on ${today}.`,
    '# REVIEW BEFORE UPLOADING TO GOOGLE. These domains were flagged toxic by an automated filter.',
    '# Disavowing good links can hurt rankings. Remove any line you are not sure about.',
    `# ${uniq.length} ${uniq.length === 1 ? 'domain' : 'domains'}.`,
    ...uniq.map((d) => `domain:${d}`),
    '',
  ].join('\n');
}
